"""美股(US)量化交易模型 —— 与 A 股/港股并列的第三套市场实现。

为什么单独一个包而不是复用 `quant_a` / `quant_hk`
----------------------------------------------------
美股的**交易机制与股票池结构**和前两个市场都不同, 直接复用会在回测里引入
系统性偏差:

| 维度 | A 股 | 港股 | 美股 |
|---|---|---|---|
| 每手股数 | 固定 100 股 | **按股各异**(20~100000) | **1 股**(无整手概念) |
| 涨跌停 | ±10%/20%/5% 硬约束 | 无(仅 VCM) | 无(仅 LULD 熔断, 不阻止成交) |
| 印花税 | 卖出 0.05% | 双边 0.1%(向上取整) | **无** |
| 主要交易费用 | 佣金 + 过户费 | 印花税 + 交易费 + 征费 + 结算费 | **SEC 规费(仅卖出) + FINRA TAF(仅卖出, 按股)** |
| 股票池陷阱 | ST/退市/次新 | 仙股/老千股/GEM | **SPAC / OTC粉单 / penny stock / 双类别** |
| 最小交易单位成本 | 整手 100 股 | 整手误差极大 | **无整手误差**(但最低佣金仍惩罚小额订单) |
| 计价货币 | CNY | HKD | **USD** |
| 历史市值 | baostock 给流通股本 | **无免费来源** | 当前股本可得, 历史股本不可得 |
| 幸存者偏差 | 有退市股 | 新浪保留退市历史 | **新浪保留退市历史**(Yahoo 不保留) |

因此本包独立实现数据/成本/引擎/因子/择时/股票池, 但**刻意保持与 A 股/港股相同的
分层与方法论**(过滤 → 因子 → 打分 → 择时 → 引擎 → 绩效), 便于三边对照与共同维护。

三条主线上的取舍(详见 `docs/10_美股方法论调研.md`)
---------------------------------------------------
1. **数据源选新浪而不是 Yahoo**: Yahoo 对**退市股零覆盖**(实测 27 个已退市代码
   全部 404), 而美股退市率远高于 A 股/港股; 新浪直连保留退市股完整历史。
   代价是新浪序列**不做分红调整**(已实测判定), 个股收益系统性低估约 1.3-2.0%/年。
2. **主流动性约束用绝对成交额而非市值分位**: 历史股本不可得,
   `dollar_volume = close × volume` 是不依赖股本的直接度量。
3. **股票池必须显式剔除 SPAC**: 美股特有陷阱, SPAC 股价恒在 10 美元面值附近、
   波动率≈0, 会稳定霸占低波动因子的最优端, 把因子排序变成噪声。

子模块
------
- `codes`    美股代码规范(股份类别 `.`/`-`/`$` 三种写法互转)、普通股/优先股/权证/SPAC 判定
- `store`    本地缓存(日线/指数/快照/元数据), 与 A 股、港股缓存分目录互不干扰
- `source`   数据源封装: 新浪美股直连(日K + 全量清单 + 实时快照)
- `costs`    美股交易成本模型(SEC 规费 / FINRA TAF / 按股佣金 / 滑点)
- `engine`   回测引擎(1 股成交 / 无涨跌停 / 先卖后买 / T+1 成交)
- `factors`  价格与量价因子(反转/动量/低波/IVOL/MAX/换手/流动性)
- `universe` 股票池过滤(SPAC/OTC/次新/penny/低流动性)
- `timing`   均线闸门 + 回撤熔断 + 波动率目标仓位
- `frames`   决策日截面因子/状态矩阵(带缓存)
- `panels`   回测引擎面板(收盘价宽表 / 可成交掩码 / 交易日历)
- `strategy` 股票池过滤、打分、择时、决策构建
- `runner`   端到端回测
"""
