"""多资产(跨市场/跨资产类别)组合程序 —— 本仓库第 4 套模型。

为什么要有第 4 套程序, 而不是继续改 A股/港股/美股
================================================
前三套模型各自独立地跑出了**同一个结论**(见 `stock_market_A/docs/03`、
`stock_market_HK/docs/09`、`stock_market_USA/docs/11`):

> 在"年化 ≥20% 且 最大回撤 ≤20%"这条线上, **单市场纯多头 + 截面选股**
> 三条路全部失败; 而且失败的方式一模一样 —— **回撤预算被市场 beta 吃光了**。

三条最硬的证据(全部是仓库里已有的实测):

| 证据 | 出处 | 数字 |
|---|---|---|
| 港股"等权持有整个流动池"(零 Alpha 的 beta) | `HK/docs/10` §2 | 训练段回撤 **26.13%** —— 连最分散的池子都吃掉 26% 预算 |
| 美股同期标普500 自身 | `USA/docs/11` §0 | 训练段 **56.78%** / 样本外 **33.92%** 回撤 |
| 港股 275 个"训练段达标"配置 | `HK/docs/10` §7.4 | 只有 **21.5%** 在样本外仍为正 |

所以本程序**不选股、不猜方向、不赌单一市场**。它换掉的是问题本身:

1. **标的从"个股"换成"资产类别"** —— 股票/利率债/信用债/黄金/白银/商品/REIT/美元,
   八个类别之间的相关性远低于个股之间, 这是唯一"免费"的分散;
2. **收益来源从"截面 alpha"换成"时序动量(趋势)"** —— 后者不需要猜对"哪只涨得多",
   只需要在多数资产上做到"涨了在里面、跌了不在里面", 且它在危机里是**正偏**的;
3. **回撤控制从"择时闸门"换成"结构性三层"** —— 波动率目标(日常刹车)
   + 趋势门(单个资产的止损) + 组合回撤调速器(总闸)。
   注意 `USA/docs/11` 已经证明**指数回撤熔断对小盘组合失效**(2022 指数只跌 25.4%,
   组合跌 44.87%), 所以这里的调速器**看的是组合自己的净值**, 不是任何指数。

与三个单市场程序的差异清单
--------------------------
| 维度 | A股/港股/美股程序 | 本程序 |
|---|---|---|
| 标的 | 个股(数百~数千只) | **资产类别 ETF(10~20 只)** |
| 收益来源 | 截面因子排序 | **时序动量(绝对趋势)** |
| 数据源 | 新浪 / baostock / 富途 | **Yahoo chart adjclose(总收益, 含分红)** |
| 幸存者偏差 | 是核心风险(退市股) | **不存在标的退市路径**(固定 ETF 篮子) |
| 分红 | 新浪序列不含分红 | **adjclose 已含分红再投资** |
| 成本 | 印花税/过户费/规费 | **几乎全是价差 + 极小额佣金** |
| 杠杆 | 不用 | **可用(上限硬约束, 且按日计融资成本)** |
| 组合层风控 | 无 | **回撤调速器(路径依赖, 本程序独有)** |
| 现金 | 零息 | **BIL 总收益(短债), 现金不是零收益** |

数据源取舍(为什么这次用 Yahoo 而不是新浪)
------------------------------------------
本仓库在美股侧明确否决过 Yahoo, 理由是"**退市股全部 404** → 幸存者偏差"。
那条理由在本用例下**不成立**, 因为:

- 本程序的标的是一组**当前仍上市的流动性 ETF**(SPY/TLT/GLD/DBC...),
  它们**没有**"退市了所以看不到"的路径 —— 幸存者偏差的前提不存在;
- 而新浪 ETF 序列有两个致命缺口(实测于本机, 见 `source.py` 顶部):
  ① **不含分红**, 对一个债券/REIT/高股息占比很高的组合是方向性偏差
  (TLT 股息率约 4%/年, 直接抹掉 4 个百分点的年化);
  ② **覆盖不全**: TLT/IEF/SHY/EMB 只有 2016 年以后的数据, 会**丢掉 2008**。

Yahoo 的 `adjclose` 是**含分红再投资的总收益**, 且覆盖到各 ETF 成立日
(SPY 1993 / TLT 2002 / GLD 2004 / DBC 2006), 于是回测能覆盖
1995 以来**每一次**权益熊市(2000-2002、2008、2020、2022)。
"""
