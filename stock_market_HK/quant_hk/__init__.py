"""港股(HKEX)量化交易模型 —— 与 A 股模型并列的第二套市场实现。

为什么单独一个包而不是复用 `quant_a.strategy`
--------------------------------------------------
港股的**交易机制与 A 股根本不同**, 直接复用会在回测里引入系统性高估:

| 维度 | A 股 | 港股 |
|---|---|---|
| 每手股数 | 固定 100 股 | **按股票各异**(腾讯100/汇丰400/长和500), 有的上万 |
| 涨跌停 | ±10%/20%/5% 硬约束 | **无涨跌停**(仅 VCM 冷静期) → 单日 -90% 会真实进净值 |
| 印花税 | 卖出单边 0.05% | **买卖双边各 0.1%**(向上取整到元) |
| 其他费用 | 过户费万0.1 | 交易费+交易征费+FRC征费+CCASS 结算费 |
| 股票池陷阱 | ST/退市/次新 | **仙股/老千股**(占数量50%+、成交额<5%)、GEM、-R 人民币柜台 |
| 汇率 | 无 | **组合以港元计价**, 需显式声明 |
| 卖空 | 散户基本不可 | 白名单 + uptick rule(本项目仍做纯多头) |

因此本包独立实现数据/成本/引擎/因子/择时, 但**刻意保持与 A 股侧相同的分层与方法论**
(过滤 → 因子 → 打分 → 择时 → 引擎 → 绩效), 便于两边对照与共同维护。

子模块
------
- `codes`    港股代码规范(5位数字.HK)、板块判定、每手股数、仙股识别
- `store`    本地缓存(日线/元数据/universe), 与 A 股缓存分目录互不干扰
- `source`   数据源封装: 新浪(可靠, 主源) + 腾讯(换手率补充) + 富途(元数据)
- `frames`   个股日线 -> 决策日截面因子/状态矩阵(带缓存)
- `panels`   回测引擎面板(后复权价 / 可成交掩码 / 每手股数)
- `costs`    港股交易成本模型
- `engine`   回测引擎(每手股数各异 / 无涨跌停 / 先卖后买)
- `strategy` 股票池过滤、因子、打分、择时、决策构建
- `runner`   端到端回测
"""
